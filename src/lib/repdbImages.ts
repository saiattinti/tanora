const imageRoot = 'https://raw.githubusercontent.com/RepDB/exercise-dataset/main/images/flat/'

export function repdbImage(exerciseId: string, pose: 'start' | 'peak' = 'start'): string | null {
  const id = exerciseImageIds[exerciseId]
  if (!id) return null
  // Holds may have just one illustration; callers can hide unavailable secondary poses.
  return imageRoot + id + '-' + pose + '.webp'
}
